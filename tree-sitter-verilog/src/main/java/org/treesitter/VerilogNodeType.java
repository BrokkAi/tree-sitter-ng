    public static VerilogNodeType from(@Nullable TSNode node) {
        if (node == null) return __NULL__;
        return fromType(node.getType());
    }

    public static VerilogNodeType fromType(@Nullable String type) {
        if (type == null) return __NULL__;
        VerilogNodeType t = LOOKUP.get(type);
        return t == null ? __NULL__ : t;
    }

    private static final Map<String, VerilogNodeType> LOOKUP = initLookup();

    private static Map<String, VerilogNodeType> initLookup() {
        HashMap<String, VerilogNodeType> m = new HashMap<>();
        for (VerilogNodeType t : values()) {
            if (t.type != null) m.put(t.type, t);
        }
        return Collections.unmodifiableMap(m);
    }
